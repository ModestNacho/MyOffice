const bootMessages = [
  "  Initializing system components...",
  "  Loading drivers...",
  "  Starting services...",
  "  Verifying system integrity...",
  "  Loading user settings...",
];

const LoadingScreen = ({ onFinish }) => {
  const [progress, setProgress] = useState(0);
  const [loadingFinished, setLoadingFinished] = useState(false);
  const [frame, setFrame] = useState(0);
  const [showPrompt, setShowPrompt] = useState(false);
  const [currentMessage, setCurrentMessage] = useState("");
  const [messageIndex, setMessageIndex] = useState(0);

  // Typing effect for boot messages
  useEffect(() => {
    if (messageIndex < bootMessages.length) {
      const currentText = bootMessages[messageIndex];
      let charIndex = 0;
      let tempMessage = ""; // Store the typed message
  
      const typingInterval = setInterval(() => {
        if (charIndex < currentText.length) {
          tempMessage += currentText[charIndex]; // Append character-by-character
          setCurrentMessage((prev) => (prev || "") + currentText[charIndex]); // Update the displayed message
          charIndex++;
        } else {
          clearInterval(typingInterval);
          setTimeout(() => {
            setCurrentMessage((prev) => prev + " - reset back to Default! \n"); // Append "OK" at the end of the full message
            setMessageIndex((prev) => prev + 1);
          }, 500); // Delay before next message
        }
      }, 50); // Typing speed
  
      return () => clearInterval(typingInterval);
    }
  }, [messageIndex]);

  useEffect(() => {
    const totalCharacters = bootMessages.reduce((sum, msg) => sum + msg.length, 0);
    const totalBootTime = totalCharacters * 50 + bootMessages.length * 500; // Typing + message delay
  
    const progressInterval = setInterval(() => {
      setProgress((prev) => {
        if (prev < 100) {
          return prev + 100 / (totalBootTime / 30); // Scale progress over totalBootTime
        } else {
          clearInterval(progressInterval);
          setLoadingFinished(true);
          setTimeout(() => setShowPrompt(true), 1000);
          return 100;
        }
      });
    }, 30);
  
    return () => clearInterval(progressInterval);
  }, []);

  useEffect(() => {
    const frameInterval = setInterval(() => {
      setFrame((prev) => (prev + 1) % frames.length); // Loop through ASCII frames
    }, 150); // Adjust speed as needed
  
    return () => clearInterval(frameInterval);
  }, []);

  const renderLoadingBar = () => {
    const barLength = 30;
    const filledLength = Math.round((progress / 100) * barLength);
    const emptyLength = barLength - filledLength;
    return `[${'='.repeat(filledLength)}${' '.repeat(emptyLength)}] ${Math.round(progress)}%`;  };

  useEffect(() => {
    const handleKeyPress = (event) => {
      if (loadingFinished && event.key === 'Enter') {
        onFinish();
      }
    };

    window.addEventListener('keydown', handleKeyPress);

    return () => {
      window.removeEventListener('keydown', handleKeyPress);
    };
  }, [loadingFinished, onFinish]);

  return (
    <div className="loading-screen">
      {/* Boot messages with typing effect */}
      {currentMessage && <pre className="boot-message">{currentMessage}</pre>}
      
      {/* ASCII Art */}
      <pre className="loading-text">
        {`
   __                ___                         
  / /  ___  ___ ____/ (_)__  ___ _               
 / /__/ _ \\/ _ \`/ _  / / _ \\/ _ \`/ _   _   _     
/____/\\___/\\_,_/\\_,_/_/_//_/\\_, / (_) (_) (_)    
                           /___/                 
        `}
      </pre>

      {/* ASCII Spinner */}
      <div className="ascii-spinner-container">
        <pre className="ascii-spinner">{frames[frame]}</pre>
      </div>

      {/* Loading Bar */}
      <pre className="loading-bar">{renderLoadingBar()}</pre>

      {/* "Press Enter" Prompt */}
      {loadingFinished && showPrompt && (
        <pre className="press-enter-text">
          Press Enter to continue... <span className="blinking-cursor">_</span>
        </pre>
      )}
    </div>
  );
};

export default LoadingScreen;